export const SYMPTOM_SLUGS = SYMPTOMS.map(s => s.slug);

export function getSymptom(slug: string): Symptom | undefined {
  return SYMPTOMS.find(s => s.slug === slug);
}

export function getRelatedSymptoms(slug: string): Symptom[] {
  const symptom = getSymptom(slug);
  if (!symptom) return [];
  return symptom.related
    .map(s => getSymptom(s))
    .filter((s): s is Symptom => s !== undefined);
}